"""Regenerate exact runtime/dev pins from this project's isolated environment."""

from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOTS = ["fastapi", "uvicorn", "pydantic", "PyYAML", "croniter", "httpx", "psycopg[binary]"]


def dependencies(roots):
    resolved = {}
    queue = [Requirement(item) for item in roots]
    while queue:
        requirement = queue.pop()
        name = canonicalize_name(requirement.name)
        if name in resolved:
            continue
        distribution = metadata.distribution(name)
        resolved[name] = distribution.version
        extras = requirement.extras or {""}
        for raw in distribution.requires or []:
            child = Requirement(raw)
            if child.marker is None or any(
                child.marker.evaluate({"extra": extra}) for extra in extras
            ):
                queue.append(child)
    return resolved


root = Path(__file__).resolve().parents[1]
runtime = dependencies(ROOTS)
(root / "requirements.lock").write_text(
    "# Exact runtime pins; generated by scripts/lock.py. Python 3.12.\n"
    + "\n".join(f"{name}=={version}" for name, version in sorted(runtime.items()))
    + "\n",
    encoding="utf-8",
)
all_installed = {
    canonicalize_name(dist.metadata["Name"]): dist.version
    for dist in metadata.distributions()
    if canonicalize_name(dist.metadata["Name"]) not in {"pipefoundry", "pyspark", "py4j"}
}
(root / "requirements-dev.lock").write_text(
    "# Runtime and verification tooling exact pins; excludes optional Spark.\n"
    + "\n".join(f"{name}=={version}" for name, version in sorted(all_installed.items()))
    + "\n",
    encoding="utf-8",
)
